# === 원-핫 인코딩 ===
def one_hot(labels, num_classes=3):
    result = np.zeros((labels.size, num_classes))
    result[np.arange(labels.size), labels] = 1
    return result

T_train_onehot = one_hot(T_train, 3)
T_test_onehot = one_hot(T_test, 3)

# 원-핫 인코딩과 데이터 정규화 전처리 과정 설명.docx 참고

network = TwoLayerNet(input_size=7, hidden_size=40, output_size=3)

# === 학습 설정 ===
iters_num = 300
train_size = X_train.shape[0]
batch_size = 100
learning_rate = 0.01

# === 학습 ===
for i in range(iters_num):

    # 미니배치 추출
    batch_mask = np.random.choice(train_size, batch_size)
    x_batch = X_train[batch_mask]
    t_batch = T_train_onehot[batch_mask]

    # 기울기 계산
    grad = network.gradient(x_batch, t_batch)

    # 가중치 갱신
    for key in ('W1', 'b1', 'W2', 'b2'):
        network.params[key] -= learning_rate * grad[key]

    # 100회마다 학습 결과 출력
    if i % 100 == 0:
        train_acc = network.accuracy(X_train, T_train_onehot)
        test_acc = network.accuracy(X_test, T_test_onehot)

        print("반복:", i)
        print("학습 정확도: {:.2f}%".format(train_acc * 100))
        print("테스트 정확도: {:.2f}%".format(test_acc * 100))
        print("----------------------")

