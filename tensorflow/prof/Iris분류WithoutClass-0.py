import numpy as np

# -------------------------------
# 1. 활성화 함수 및 손실함수
# -------------------------------
def sigmoid(x):
    return 1 / (1 + np.exp(-x))

def softmax(x):
    if x.ndim == 2:
        x = x - np.max(x, axis=1, keepdims=True)
        return np.exp(x) / np.sum(np.exp(x), axis=1, keepdims=True)
    x = x - np.max(x)
    return np.exp(x) / np.sum(np.exp(x))

def cross_entropy_error(y, t, eps=1e-7):
    if y.ndim == 1:
        y = y.reshape(1, -1)
        t = t.reshape(1, -1)
    batch_size = y.shape[0]
    return -np.sum(t * np.log(y + eps)) / batch_size


# -------------------------------
# 2. 수치 미분
# -------------------------------
def _numerical_gradient_1d(f, x):  # p.127
    h = 1e-4
    grad = np.zeros_like(x)
    for idx in range(x.size):
        tmp = x[idx]
        x[idx] = tmp + h
        fxh1 = f(x)
        x[idx] = tmp - h
        fxh2 = f(x)
        grad[idx] = (fxh1 - fxh2) / (2 * h)
        x[idx] = tmp
    return grad

def numerical_gradient(f, X):
    if X.ndim == 1:
        return _numerical_gradient_1d(f, X)
    else:
        grad = np.zeros_like(X)
        for idx, x in enumerate(X):
            grad[idx] = _numerical_gradient_1d(f, x)
        return grad


# -------------------------------
# 3. 가중치 초기화
# -------------------------------

np.random.seed(0)

params = {}
params['W1'] = np.random.randn(4, 6)
params['b1'] = np.zeros(6)
params['W2'] = np.random.randn(6, 3)
params['b2'] = np.zeros(3)


# -------------------------------
# 4. 순전파 함수
# -------------------------------
def predict(x):
    W1, b1 = params['W1'], params['b1']
    W2, b2 = params['W2'], params['b2']
    
    a1 = np.dot(x, W1) + b1
    z1 = sigmoid(a1)
    a2 = np.dot(z1, W2) + b2
    y = softmax(a2)
    return y


# -------------------------------
# 5. 손실 및 정확도 계산
# -------------------------------
def loss(x, t):
    y = predict(x)
    return cross_entropy_error(y, t)

def accuracy(x, t):
    y = predict(x)
    y = np.argmax(y, axis=1)
    t = np.argmax(t, axis=1)
    return np.sum(y == t) / float(x.shape[0])


# -------------------------------
# 6. 수치미분 기반 기울기 계산
# -------------------------------
def my_numerical_gradient(x, t):
    loss_W = lambda _: loss(x, t)
    grads = {}
    grads['W1'] = numerical_gradient(loss_W, params['W1'])
    grads['b1'] = numerical_gradient(loss_W, params['b1'])
    grads['W2'] = numerical_gradient(loss_W, params['W2'])
    grads['b2'] = numerical_gradient(loss_W, params['b2'])
    return grads
# loss_W : 현재 신경망의 손실함수, input과 output으로 신경망 성능을 측정하는 함수

